-- 1. ELIMINACION
DROP TABLE IF EXISTS audit_log;
DROP TABLE IF EXISTS users;
DROP TABLE IF EXISTS comunas;
DROP TABLE IF EXISTS regions;
DROP TABLE IF EXISTS roles;

-- 2. TABLAS MAESTRAS
CREATE TABLE roles (
    id   INT PRIMARY KEY,
    name VARCHAR(50) UNIQUE NOT NULL CHECK (name IN ('ADMIN', 'SELLER', 'CUSTOMER'))
);

CREATE TABLE regions (
    id    INT PRIMARY KEY,
    name  VARCHAR(120) UNIQUE NOT NULL,
    orden INT NOT NULL
);

CREATE TABLE comunas (
    id        INT PRIMARY KEY,
    name      VARCHAR(120) NOT NULL,
    region_id INT NOT NULL REFERENCES regions(id)
);

CREATE INDEX idx_comunas_region ON comunas(region_id);

CREATE TABLE users (
    id               BIGSERIAL PRIMARY KEY,
    run              VARCHAR(12) UNIQUE NOT NULL,
    email            VARCHAR(150) UNIQUE NOT NULL,
    password         VARCHAR(255) NOT NULL,
    nombre           VARCHAR(100) NOT NULL,
    apellidos        VARCHAR(100),
    fecha_nacimiento DATE,
    role_id          INT REFERENCES roles(id),
    region_id        INT REFERENCES regions(id),
    comuna_id        INT REFERENCES comunas(id),
    direccion        VARCHAR(255),
    activo           BOOLEAN DEFAULT TRUE,
    created_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- audit_log se mantiene igual; user_id es BIGINT para referenciar users.id (BIGSERIAL).
CREATE TABLE audit_log (
    id         SERIAL PRIMARY KEY,
    user_id    BIGINT REFERENCES users(id),
    accion     VARCHAR(100) NOT NULL,
    ip_address VARCHAR(45),
    fecha_hora TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

